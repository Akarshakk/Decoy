import { useState } from 'react';
import { BenignTable, CatchMatrix, LatencyChart, SessionHistograms, StopBars } from '../components/EvalCharts';
import { Frame } from '../components/ui';
import { fmtDateTime } from '../live/labels';
import { headline, spotCheck, useEvalResults, weaknesses, type EvalFile, type SpotCheck } from '../live/evals';

const pct = (x: number, d = 0) => `${(100 * x).toFixed(d)}%`;
const SPOT_SEEDS = 5;

export function Evals() {
  const { data, error } = useEvalResults();
  const header = (
    <header className="topbar">
      <p className="crumb"><b>Evaluations</b>{data && <span className="muted"> {data.meta.trialsPerFamily} trials per attack, seeds {data.meta.seeds[0]}–{data.meta.seeds[1]}</span>}</p>
      {data && <div className="topbar-actions"><span className="pill-status">Synthetic data</span></div>}
    </header>
  );
  if (!data) return <div className="main-col">{header}<div className="empty"><p>{error ?? 'Loading the eval results…'}</p></div></div>;
  return <div className="main-col">{header}<Report r={data} /></div>;
}

function Report({ r }: { r: EvalFile }) {
  const h = headline(r);
  const weak = weaknesses(r);
  const full = r.configs.find(c => c.id === 'full')!, cred = r.configs.find(c => c.id === 'credentials')!;
  return (
    <section className="canvas" aria-label="Evaluation results">
      <div className="page">
        <p className="ev-banner small">
          Every session, attack and document on this page was generated by the eval harness and decided by the same engine that runs the console.
          Seeds {r.meta.seeds[0]}–{r.meta.seeds[1]} are the test split: nothing was tuned on them. Generated {fmtDateTime(Date.parse(r.run.generatedAt))} at commit <span className="mono">{r.run.commit}</span>{r.run.dirty ? ' with uncommitted changes' : ''}.
        </p>

        <div className="cards-3">
          <Frame className="card ev-stat">
            <h2 className="card-h">Attacks stopped</h2>
            <p className="ev-big num">{pct(h.full.rate, 1)}</p>
            <p className="small muted">{h.full.k} of {h.full.n} trials across {h.families} attack families, full engine (95% interval {pct(h.full.ci[0], 1)} to {pct(h.full.ci[1], 1)}). {cred.label}: {pct(h.credentials.rate, 1)}.</p>
          </Frame>
          <Frame className="card ev-stat">
            <h2 className="card-h">Everyday work flagged</h2>
            <p className="ev-big num">{h.everyday.flagged} <span className="ev-of">of {h.everyday.sessions}</span></p>
            <p className="small muted">Ordinary sessions across {h.everyday.cohorts} agents that the full engine held or alarmed on. Shifted work is below, and it is worse.</p>
          </Frame>
          {r.latency && (
            <Frame className="card ev-stat">
              <h2 className="card-h">Inline checks, p95</h2>
              <p className="ev-big num">{r.latency.inlineUs.p95} <span className="ev-of">µs</span></p>
              <p className="small muted">Token, role, data flow and credential context per call, over {r.latency.calls.toLocaleString('en-US')} calls. The whole decision: p95 {r.latency.totalUs.p95} µs.</p>
            </Frame>
          )}
        </div>

        <Frame className="card">
          <h2 className="card-h">Attacks caught, by detector set <span className="muted">share of {r.meta.trialsPerFamily} seeded trials; the whisker is the 95% Wilson interval</span></h2>
          <CatchMatrix r={r} />
          <details className="ev-defs small">
            <summary>What each family does, and what counts as caught</summary>
            <ul>
              {r.attacks.map(a => <li key={a.id}><b>{a.label}.</b> {a.summary} It counts as a miss when {a.damage}.</li>)}
            </ul>
            <p>The credential gate (signature, expiry, version, scope) runs in every column. {full.label} adds every detector, the drift accumulator and the decoy tripwire.</p>
          </details>
        </Frame>

        <div className="cards-2 ev-pair">
          <div className="ev-col">
            <Frame className="card">
              <h2 className="card-h">When single-session attacks were stopped <span className="muted">full engine</span></h2>
              <StopBars attacks={r.attacks} />
            </Frame>
            {r.latency && (
              <Frame className="card">
                <h2 className="card-h">Latency per call <span className="muted">Node {r.run.node}, the machine that ran the eval</span></h2>
                <LatencyChart l={r.latency} />
                <p className="small muted">
                  Inline checks are token verification plus S1, S3 and S5. The whole decision adds S2, S4, S6, drift, fusion, the explanation and, for calls that run,
                  the simulated backend and fingerprinting its result. The first call of a session takes p50 {r.latency.firstInSession.p50} µs (it refits the volume
                  bands learned when the last session ended); later calls take p50 {r.latency.laterInSession.p50} µs. The ledger write is not included.
                </p>
              </Frame>
            )}
          </div>
          <Frame className="card">
            <h2 className="card-h">Sessions until slow attacks were caught <span className="muted">full engine</span></h2>
            <SessionHistograms attacks={r.attacks} />
          </Frame>
        </div>

        <Frame className="card">
          <h2 className="card-h">Cost to normal work <span className="muted">{r.meta.sessionsPerCohort} measured sessions per cohort</span></h2>
          <BenignTable benign={r.benign} />
          <p className="small muted">A session is flagged when any call is held or worse, any call does not run, or a drift alarm fires when it ends. Shifted cohorts are legitimate but unusual work.</p>
        </Frame>

        <Frame className="card">
          <h2 className="card-h">Where it falls short <span className="muted">from this run</span></h2>
          <ul className="ev-weak">
            {weak.map(w => (
              <li key={w.id} className={`ev-weak-${w.kind}`}>
                <b>{w.title}</b>
                <span className="small">{w.detail}</span>
              </li>
            ))}
            <li className="ev-weak-expected">
              <b>D10, calls that bypass the gateway: not measured</b>
              <span className="small">An agent that calls an HTTP endpoint directly never reaches the engine, so nothing here can score it. Network telemetry taps are the production answer.</span>
            </li>
          </ul>
        </Frame>

        <Frame className="card">
          <h2 className="card-h">Check it yourself</h2>
          <Spot r={r} />
          <p className="small">Reproduce the whole file with <code className="mono">{r.run.command}</code> ({r.run.seconds}s on the machine that made it). The markdown summary is <code className="mono">reports/eval.md</code>.</p>
        </Frame>
      </div>
    </section>
  );
}

/** Replays the first few test seeds of every family in this browser and compares the outcomes with the file. */
function Spot({ r }: { r: EvalFile }) {
  const [state, setState] = useState<{ done: number; total: number; result: SpotCheck[] | null } | null>(null);
  const run = async () => {
    setState({ done: 0, total: r.attacks.length * 2, result: null });
    const result = await spotCheck(r, SPOT_SEEDS, ['credentials', 'full'], (done, total) => setState({ done, total, result: null }));
    setState({ done: result.length, total: result.length, result });
  };
  const bad = state?.result?.filter(x => !x.match) ?? [];
  return (
    <div className="ev-spot">
      <p className="small">Replay seeds {r.meta.seeds[0]}–{r.meta.seeds[0] + SPOT_SEEDS - 1} of every attack family, credentials only and full, through the engine in this tab. The engine is deterministic, so every outcome should match the file exactly.</p>
      <div className="ev-spot-row">
        <button className="btn btn-ink" onClick={run} disabled={!!state && !state.result}>{state && !state.result ? `Replaying ${state.done} of ${state.total}…` : state?.result ? 'Replay again' : 'Replay in this browser'}</button>
        {state?.result && (
          <span className={`pill-status ${bad.length ? 'is-bad' : ''}`}>
            {bad.length ? `✕ ${bad.length} of ${state.result.length} differ` : `✓ ${state.result.length} of ${state.result.length} match`}
          </span>
        )}
      </div>
      {state?.result && (
        <ul className="ev-spot-list mono small">
          {state.result.map(x => (
            <li key={`${x.family}:${x.config}`} className={x.match ? '' : 'is-bad'}>
              <span>{r.attacks.find(a => a.id === x.family)!.label} · {r.configs.find(c => c.id === x.config)!.label}</span>
              <span>{[...x.got].map(b => (b === '1' ? '●' : '○')).join('')}{x.match ? '' : ` (file ${x.expected})`}</span>
            </li>
          ))}
        </ul>
      )}
      {state?.result && <p className="small muted">● caught, ○ got through, one mark per seed.</p>}
    </div>
  );
}
