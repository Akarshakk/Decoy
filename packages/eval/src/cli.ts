// npm run eval [-- --split dev]
// Writes apps/console/public/eval/results.json (read by the Evaluations page) and reports/eval.md.
import { execSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { breakdown, evaluate, SPLITS, type Results } from './harness';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const split = (process.argv.includes('--split') ? process.argv[process.argv.indexOf('--split') + 1] : 'test') as keyof typeof SPLITS;
if (!(split in SPLITS)) throw new Error(`unknown split ${split}; use dev or test`);

const t0 = performance.now();
const results = await evaluate({ split, onProgress: m => process.stdout.write(`\r\x1b[K${m}`) });
const seconds = Math.round((performance.now() - t0) / 1000);
process.stdout.write('\r\x1b[K');

const git = (cmd: string) => { try { return execSync(cmd, { cwd: root }).toString().trim(); } catch { return null; } };
const out = {
  ...results,
  run: {
    generatedAt: new Date().toISOString(), commit: git('git rev-parse --short HEAD'), dirty: !!git('git status --porcelain'),
    node: process.version, seconds, command: split === 'test' ? 'npm run eval' : `npm run eval -- --split ${split}`,
  },
};

const json = resolve(root, 'apps/console/public/eval/results.json');
mkdirSync(dirname(json), { recursive: true });
writeFileSync(json, JSON.stringify(out) + '\n');
const md = resolve(root, 'reports/eval.md');
mkdirSync(dirname(md), { recursive: true });
writeFileSync(md, report(results, out.run));
console.log(`wrote ${json}\nwrote ${md}\n${seconds}s`);

function report(r: Results, run: typeof out.run) {
  const pct = (x: number) => `${(100 * x).toFixed(1)}%`;
  const ci = (c: [number, number]) => `${pct(c[0])}–${pct(c[1])}`;
  const L: string[] = [];
  L.push('# Swaroop evaluation', '');
  L.push(`Synthetic data: every session, attack and document is generated by \`packages/eval\` and decided by the real engine. Seeds ${r.meta.seeds[0]}–${r.meta.seeds[1]} (${r.meta.split} split), ${r.meta.trialsPerFamily} trials per attack family and ${r.meta.sessionsPerCohort} measured sessions per benign cohort. Generated ${run.generatedAt} at commit ${run.commit}${run.dirty ? ' (uncommitted changes)' : ''}, Node ${run.node}, ${run.seconds}s. Reproduce: \`${run.command}\`.`, '');

  L.push('## Attacks caught (Wilson 95% CI)', '');
  L.push(`| Family | ${r.configs.map(c => c.label).join(' | ')} |`, `|---|${r.configs.map(() => '---').join('|')}|`);
  for (const a of r.attacks) L.push(`| ${a.label}${a.expectedMiss ? ' (expected miss)' : ''} | ${r.configs.map(c => `${pct(a.byConfig[c.id]!.rate)} (${ci(a.byConfig[c.id]!.ci)})`).join(' | ')} |`);
  L.push('', 'Caught means the attacker’s goal never happened. Damage per family:', '');
  for (const a of r.attacks) L.push(`- **${a.label}**: ${a.summary} Damage = ${a.damage}.`);

  L.push('', '## Time to detect (full engine, caught trials)', '');
  for (const a of r.attacks) {
    const xs = a.byConfig.full?.detectAt.filter((x): x is number => x !== null) ?? [];
    if (!xs.length) { L.push(`- ${a.label}: none caught`); continue; }
    const hist = new Map<number, number>(); xs.forEach(x => hist.set(x, (hist.get(x) ?? 0) + 1));
    L.push(`- ${a.label}: stopped at ${a.unit === 'calls' ? 'attack call' : 'session'} ${[...hist].sort((p, q) => p[0] - q[0]).map(([k, n]) => `${k} (${n})`).join(', ')}`);
  }

  L.push('', '## Misses of the full engine, by variant', '');
  for (const a of r.attacks) {
    const full = a.byConfig.full; if (!full) continue;
    const weak = breakdown(a.variants, full.caught).filter(b => b.caught < b.n);
    if (weak.length) L.push(`- ${a.label}: ${weak.map(b => `${b.field} = ${b.value}: ${b.caught}/${b.n}`).join('; ')}`);
  }

  L.push('', '## Benign disruption', '');
  L.push('| Cohort | Config | Sessions flagged | Calls blocked | Drift alarms | Max score |', '|---|---|---|---|---|---|');
  for (const b of r.benign) for (const c of r.configs) {
    const x = b.byConfig[c.id]!;
    L.push(`| ${b.label} | ${c.label} | ${x.flagged}/${x.sessions} (${pct(x.flaggedRate.rate)}) | ${x.blocked}/${x.calls} (${pct(x.blockedRate.rate)}) | ${x.alarms} | ${x.maxScore} |`);
  }
  L.push('', 'A session is flagged when any call scores HOLD or worse, any call does not run, or a drift alarm fires at its end.');

  if (r.latency) {
    const l = r.latency;
    L.push('', `## Latency (${l.calls} benign calls, full engine)`, '');
    L.push(`- Inline checks (token, S1, S3, S5): p50 ${l.inlineUs.p50} µs, p95 ${l.inlineUs.p95} µs, p99 ${l.inlineUs.p99} µs`);
    L.push(`- Whole decision (adds S2, S4, S6, drift, fusion, the explanation, the simulated backend and fingerprinting its result): p50 ${l.totalUs.p50} µs, p95 ${l.totalUs.p95} µs, p99 ${l.totalUs.p99} µs`);
    L.push(`- First call of a session (refits the volume bands learned at the last session end): p50 ${l.firstInSession.p50} µs; later calls: p50 ${l.laterInSession.p50} µs`);
    L.push(`- By tool (p50): ${l.byTool.map(t => `${t.tool} ${t.totalUs.p50} µs`).join(', ')}`);
    L.push('', 'Measured in Node on the machine that ran the eval; the ledger write is not included. Numbers vary between runs and machines.');
  }

  L.push('', '## Not measured', '', '- D10: an agent that calls an HTTP endpoint directly, around the gateway, is not observable here. Telemetry taps on the network are the production answer.');
  return L.join('\n') + '\n';
}
